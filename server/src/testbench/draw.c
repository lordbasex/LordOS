void d_fill(Surf *s, int x, int y, int w, int h, uint32_t c) {
    int x0 = x < 0 ? 0 : x, y0 = y < 0 ? 0 : y, x1 = x + w > s->w ? s->w : x + w, y1 = y + h > s->h ? s->h : y + h;
    for (int j = y0; j < y1; j++) {
        uint32_t *row = s->px + (size_t)j * s->stride;
        for (int i = x0; i < x1; i++) row[i] = c;
    }
}

void d_frame(Surf *s, int x, int y, int w, int h, int t, uint32_t c) {
    d_fill(s, x, y, w, t, c);
    d_fill(s, x, y + h - t, w, t, c);
    d_fill(s, x, y, t, h, c);
    d_fill(s, x + w - t, y, t, h, c);
}

void d_circle(Surf *s, int cx, int cy, int r, uint32_t c) {
    for (int y = -r; y <= r; y++)
        for (int x = -r; x <= r; x++)
            if (x * x + y * y <= r * r) {
                int px = cx + x, py = cy + y;
                if (px >= 0 && px < s->w && py >= 0 && py < s->h) s->px[(size_t)py * s->stride + px] = c;
            }
}

int d_text(Surf *s, int x, int y, int scale, uint32_t c, const char *t) {
    int x0 = x;
    for (; *t; t++) {
        int ch = toupper((unsigned char)*t);
        if (ch == '`') ch = '\'';              /* the grave accent: drawn as the apostrophe */
        if (ch < 32 || ch > 95) ch = '?';
        const uint8_t *g = FONT[ch - 32];
        for (int row = 0; row < 7; row++)
            for (int col = 0; col < 5; col++)
                if (g[row] & (1 << (4 - col))) d_fill(s, x + col * scale, y + row * scale, scale, scale, c);
        x += 6 * scale;
    }
    return x - x0;
}

int d_text_w(const char *t, int scale) { int n = (int)strlen(t); return n ? n * 6 * scale - scale : 0; }

void d_text_c(Surf *s, int cx, int cy, int scale, uint32_t c, const char *t) {
    d_text(s, cx - d_text_w(t, scale) / 2, cy - 7 * scale / 2, scale, c, t);
}
