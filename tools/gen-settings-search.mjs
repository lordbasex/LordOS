#!/usr/bin/env node
// gen-settings-search.mjs — writes apps/settings/searchkeys.js: for each Settings section, the locale keys of the text
// its page shows (row labels, choices, short notes), so Settings' search finds a section by any of them (BUG-18 of the
// ws170 QA: "Acomodar" found nothing, though Desktop & Dock has "Acomodar ventanas en los bordes de la pantalla").
//
// It reads the section's component (apps/settings/index.jsx GROUPS) and, recursively, every component of
// apps/settings it draws, and keeps each literal key passed to t/tr/tOptional ('ns.key') whose English text is short
// (at most 80 characters: labels, not paragraphs). Keys built at run time are not seen.
//   node tools/gen-settings-search.mjs           write the file
//   node tools/gen-settings-search.mjs --check   exit 1 if it is out of date (server/tests/settings_search_test.mjs)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'apps/settings');
const out = path.join(dir, 'searchkeys.js');
const MAX_TEXT = 80;

const files = fs.readdirSync(dir).filter((f) => f.endsWith('.jsx')).sort();
const sources = Object.fromEntries(files.map((f) => [f, fs.readFileSync(path.join(dir, f), 'utf8')]));

// a top-level function's source: from its line to the first line that is only "}"
function body(name) {
  for (const f of files) {
    const s = sources[f];
    const m = new RegExp(`^(?:export )?function ${name}\\(`, 'm').exec(s);
    if (!m) continue;
    const end = s.indexOf('\n}', m.index);
    return s.slice(m.index, end < 0 ? s.length : end + 2);
  }
  return null;
}

const english = {};
for (const f of fs.readdirSync(path.join(root, 'assets/locales/en'))) {
  if (!f.endsWith('.json')) continue;
  const ns = f.slice(0, -5);
  for (const [k, v] of Object.entries(JSON.parse(fs.readFileSync(path.join(root, 'assets/locales/en', f), 'utf8')))) english[`${ns}.${k}`] = v;
}

function keysOf(component) {
  const seen = new Set(), keys = new Set();
  const walk = (name, depth) => {
    if (seen.has(name) || depth > 6) return;
    seen.add(name);
    const src = body(name);
    if (!src) return;
    for (const m of src.matchAll(/\b(?:t|tr|tOptional)\(\s*'([a-z][A-Za-z0-9]*\.[A-Za-z0-9_.-]+)'/g)) {
      const v = english[m[1]];
      if (typeof v === 'string' && v.length <= MAX_TEXT) keys.add(m[1]);
    }
    for (const m of src.matchAll(/<([A-Z][A-Za-z0-9]*)/g)) walk(m[1], depth + 1);
  };
  walk(component, 0);
  return [...keys].sort();
}

// the sections, as index.jsx lists them: [id, Component, …]
const index = sources['index.jsx'];
const groups = /const GROUPS = \[([\s\S]*?)\n\];/.exec(index);
if (!groups) { console.error('gen-settings-search: GROUPS not found in apps/settings/index.jsx'); process.exit(1); }
const sections = [...groups[1].matchAll(/\['([a-z]+)', ([A-Za-z]+)/g)].map((m) => [m[1], m[2]]);
let text = '// searchkeys.js — GENERATED by tools/gen-settings-search.mjs; do not edit by hand. For each Settings section, the locale\n'
  + '// keys of the short text its page shows: Settings\' search finds the section by any of them (apps/settings/searchmodel.js).\n'
  + 'export const SECTION_KEYS = {\n';
for (const [id, comp] of sections) text += `  ${id}: ${JSON.stringify(keysOf(comp))},\n`;
text += '};\n';

if (process.argv.includes('--check')) {
  const now = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (now !== text) { console.error('apps/settings/searchkeys.js is out of date: node tools/gen-settings-search.mjs'); process.exit(1); }
  process.exit(0);
}
fs.writeFileSync(out, text);
console.log(`apps/settings/searchkeys.js: ${sections.length} sections, ${sections.reduce((a, [, c]) => a + keysOf(c).length, 0)} keys`);
