#!/usr/bin/env node
// Writes the Wayland protocol table from its one source of truth, docs/wayland-protocols.json, and the conformance
// results recorded by tools/wl-conformance.mjs (docs/wayland-conformance.json, with the screenshots of
// docs/wayland-proofs/):
//   (a) the generated sections of docs/WAYLAND.md, between the BEGIN/END marker comments (the protocol table, and
//       the per-item conformance table in "Conformance");
//   (b) web/content/wayland/protocols.json, the data of lordos.org/wayland-protocols-table/ (web/build.mjs).
//
//   node tools/gen-wayland-table.mjs            # write both
//   node tools/gen-wayland-table.mjs --check    # exit 1 if either is stale or the JSON is invalid (the drift test)
//
// When lord-server gains, loses or bumps a global: edit that protocol's `lordos` entry in the JSON (status,
// globals with their versions, since/bumped, note, checked, checkedDate) and run this. KWin's and Mutter's
// columns come from wayland.app: tools/wayland-app-import.mjs. server/tests/wayland_table_test.mjs checks the
// JSON against the wl_global_create calls in server/src/wl and runs --check.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(REPO, 'docs/wayland-protocols.json');
const DOC = path.join(REPO, 'docs/WAYLAND.md');
const WEB = path.join(REPO, 'web/content/wayland/protocols.json');
export const CONF = path.join(REPO, 'docs/wayland-conformance.json');
export const PROOFS = path.join(REPO, 'docs/wayland-proofs');
const BEGIN = '<!-- BEGIN wayland-protocols table: generated by tools/gen-wayland-table.mjs from docs/wayland-protocols.json; edit the JSON, not this -->';
const END = '<!-- END wayland-protocols table -->';
const CBEGIN = '<!-- BEGIN wayland-conformance table: generated by tools/gen-wayland-table.mjs from docs/wayland-conformance.json; record a new run, do not edit this -->';
const CEND = '<!-- END wayland-conformance table -->';
// how deep an item was tested (the site's "Depth" column):
//   complete: protocol-specific tests of every request, event and error, all passed, nothing skipped;
//   partial:  protocol-specific tests, but a point was skipped headless (no pointer over the windows, ...);
//   general:  the static code check (every request handled, every event sent, every error raised) and the generic
//             bind at every version (X11: the unit tests), with no flow of its own in the tool yet;
//   code:     only the static code check: the global can't be used headless (drm-lease needs a headset,
//             xwayland_shell is offered to Xwayland only), or the X11 item has nothing to run.
export const DEPTHS = ['complete', 'partial', 'general', 'code'];
// X11 proof screenshots are docs/wayland-proofs/x11-<item id>.png; the ones named otherwise say here which item they prove
export const X11_PROOF_ITEM = { 'x11-always-on-top.png': 'ewmh.wm_state' };
export const STATUSES = ['supported', 'partial', 'on-purpose', 'missing'];
export const CATEGORIES = ['core', 'stable', 'staging', 'unstable', 'experimental', 'wlr', 'kde', 'other'];

export const category = (p) => (p.source === 'core' ? 'core'
  : p.source === 'wayland-protocols' ? p.stability
  : p.source === 'wlr-protocols' ? 'wlr' : p.source === 'kde-protocols' ? 'kde' : 'other');
const has = (m) => !!m && Object.keys(m).length > 0;
// the version shown for a compositor: its first advertised global's
const ver = (p, m) => { const g = p.globals.find((x) => m && m[x] != null); return g ? m[g] : null; };

export function load(file = SRC) { return JSON.parse(fs.readFileSync(file, 'utf8')); }
// the conformance run and its screenshots (null when no run is recorded)
export function loadConf(file = CONF, dir = PROOFS) {
  if (!fs.existsSync(file)) return null;
  const c = JSON.parse(fs.readFileSync(file, 'utf8'));
  const pj = path.join(dir, 'proofs.json');
  c.proofs = fs.existsSync(pj) ? JSON.parse(fs.readFileSync(pj, 'utf8')) : { results: [] };
  c.proofFiles = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith('.png')).sort() : [];
  return c;
}

// Strict shapes for every value. Part of the JSON comes from wayland.app (tools/wayland-app-import.mjs), so nothing
// outside these shapes reaches docs/WAYLAND.md or the site (which also escapes every value).
export const SOURCES = ['core', 'wayland-protocols', 'wlr-protocols', 'kde-protocols', 'hyprland-protocols', 'cosmic-protocols', 'weston-protocols', 'treeland-protocols', 'river-protocols', 'gamescope-protocols', 'external'];
export const STABILITIES = ['stable', 'staging', 'unstable', 'experimental'];
export const RE_ID = /^[a-z][a-z0-9_-]*$/;          // protocol ids: xdg-shell, wayland-wl_seat
export const RE_GLOBAL = /^[a-z][a-z0-9_]*$/;        // interface names: xdg_wm_base
export const RE_URL = /^https:\/\/wayland\.app\/protocols\/[a-z0-9_#-]*$/;
export const RE_VER = /^\d+(\.\d+){1,3}$/;          // a LordOS version: 0.8.9.5
export const RE_DATE = /^\d{4}-\d{2}-\d{2}$/;
export const RE_CVER = /^[0-9][0-9.]{0,15}$/;        // a compositor's version: 6.7, 51
export const isVersion = (v) => Number.isInteger(v) && v > 0 && v < 1000;
// free text (names, summaries, notes): no markup, no control characters, bounded
export const isText = (x, max = 700) => typeof x === 'string' && x.length <= max && !/[<>\u0000-\u001f\u007f]/.test(x);

function versionMap(m, at, errs) {
  if (!m || typeof m !== 'object' || Array.isArray(m)) { errs.push(`${at} must be an object {interface: version}`); return; }
  for (const [g, v] of Object.entries(m)) {
    if (!RE_GLOBAL.test(g)) errs.push(`${at}: bad interface name ${JSON.stringify(g)}`);
    if (!isVersion(v)) errs.push(`${at}.${g}: version must be a positive integer, not ${JSON.stringify(v)}`);
  }
}

export function validate(d) {
  const errs = [];
  const ids = new Set();
  const c = d.compared || {};
  if (!RE_DATE.test(c.date || '') || c.source !== 'https://wayland.app/protocols/') errs.push('compared: needs date (YYYY-MM-DD) and source https://wayland.app/protocols/');
  for (const k of ['kwin', 'mutter']) if (!c[k] || !RE_CVER.test(String(c[k].version)) || !RE_DATE.test(c[k].dataDate || '') || !isText(c[k].name, 40) || !isText(c[k].desktop, 40)) errs.push(`compared.${k}: needs name, desktop, version and dataDate`);
  if (!Array.isArray(d.protocols)) return errs.concat('protocols must be a list');
  for (const p of d.protocols) {
    const at = `${typeof p.id === 'string' && RE_ID.test(p.id) ? p.id : JSON.stringify(p.id)}:`;
    if (typeof p.id !== 'string' || !RE_ID.test(p.id)) errs.push(`${at} id must match ${RE_ID}`);
    if (ids.has(p.id)) errs.push(`${at} duplicate id`);
    ids.add(p.id);
    if (!isText(p.name, 120) || !isText(p.summary, 300)) errs.push(`${at} name and summary must be plain text`);
    if (!SOURCES.includes(p.source)) errs.push(`${at} source must be one of ${SOURCES.join(', ')}`);
    if (!STABILITIES.includes(p.stability)) errs.push(`${at} stability must be one of ${STABILITIES.join(', ')}`);
    if (!CATEGORIES.includes(category(p))) errs.push(`${at} bad category`);
    if (typeof p.url !== 'string' || !RE_URL.test(p.url)) errs.push(`${at} url must be a https://wayland.app/protocols/ address`);
    if (p.deprecated != null && typeof p.deprecated !== 'boolean') errs.push(`${at} deprecated must be true or false`);
    if (!Array.isArray(p.globals) || !p.globals.every((g) => typeof g === 'string' && RE_GLOBAL.test(g))) { errs.push(`${at} globals must be a list of interface names`); continue; }
    versionMap(p.kwin, `${at} kwin`, errs);
    versionMap(p.mutter, `${at} mutter`, errs);
    const L = p.lordos;
    if (!L || !STATUSES.includes(L.status)) { errs.push(`${at} lordos.status must be one of ${STATUSES.join(', ')}`); continue; }
    versionMap(L.globals || {}, `${at} lordos.globals`, errs);
    const lg = Object.keys(L.globals || {});
    if ((L.status === 'supported' || L.status === 'partial') !== lg.length > 0) errs.push(`${at} a ${L.status} protocol ${lg.length ? 'lists' : 'needs'} lordos.globals`);
    for (const g of lg) if (!p.globals.includes(g)) errs.push(`${at} lordos global ${g} is not one of the row's globals`);
    if ((L.status === 'on-purpose' || L.status === 'partial') && !L.note) errs.push(`${at} ${L.status} needs a note saying why`);
    if (L.note != null && !isText(L.note)) errs.push(`${at} lordos.note must be plain text`);
    if (!isText(L.checked, 200) || !L.checked || !RE_DATE.test(L.checkedDate || '')) errs.push(`${at} lordos needs checked (plain text) and checkedDate (YYYY-MM-DD)`);
    if (L.since != null && !RE_VER.test(L.since)) errs.push(`${at} lordos.since must be a version like 0.8.9.5`);
    if (L.libwayland != null && typeof L.libwayland !== 'boolean') errs.push(`${at} lordos.libwayland must be true or false`);
    for (const [g, b] of Object.entries(L.bumped || {})) if (!lg.includes(g) || !b || !RE_VER.test(b.in || '') || !isVersion(b.from)) errs.push(`${at} bumped.${g} needs from (a version number), in (a LordOS version) and a current global`);
  }
  return errs;
}

export const RE_X11 = /^[a-z][a-z0-9]*(\.[a-z0-9_]+)?$/;   // an X11 item: ewmh.wm_state, xdnd
export const RE_PNG = /^[a-z0-9][a-z0-9_.-]{0,120}\.png$/;    // a proof screenshot in docs/wayland-proofs/ (named after the globals it proves)
export const RE_PROOF = /^[a-z0-9][a-z0-9_.-]{0,120}$/;
export const RE_COMMIT = /^[0-9a-f]{7,40}$/;
export const RE_PKGVER = /^[0-9A-Za-z.:+~-]{1,40}$/;          // a Debian package version: 2:24.1.6-1
const isScore = (x) => typeof x === 'number' && Number.isFinite(x) && x >= 0 && x <= 100;
const isCount = (x) => Number.isInteger(x) && x >= 0 && x < 100000;

// the conformance part of the site's copy; returns the proof ids it accepted
function validateConfWeb(C, ids, errs) {
  const proofIds = new Set();
  if (C === null) return proofIds;
  if (!C || typeof C !== 'object' || Array.isArray(C)) { errs.push('conformance must be an object or null'); return proofIds; }
  if (!RE_DATE.test(C.date || '') || !RE_COMMIT.test(C.commit || '') || typeof C.dirty !== 'boolean' || C.tool !== 'tools/wl-conformance.mjs' || !isCount(C.schema)) errs.push('conformance: bad date, commit, dirty, tool or schema');
  const E = C.env || {};
  if (!RE_PKGVER.test(E.waylandProtocols || '') || !RE_PKGVER.test(E.libwayland || '') || !RE_PKGVER.test(E.xwayland || '') || !isText(E.mode, 80)) errs.push('conformance.env: bad versions or mode');
  const S = C.summary || {};
  for (const k of ['protocols', 'complete', 'x11Items', 'x11Complete']) if (!isCount(S[k])) errs.push(`conformance.summary.${k} must be a count`);
  for (const k of ['mean', 'x11Mean']) if (!isScore(S[k])) errs.push(`conformance.summary.${k} must be 0-100`);
  if (!Array.isArray(C.proofs)) errs.push('conformance.proofs must be a list');
  else for (const p of C.proofs) {
    if (!p || !RE_PROOF.test(p.id || '') || !RE_PNG.test(p.png || '') || !['wayland', 'x11'].includes(p.kind) || !isText(p.app, 120) || !isText(p.version, 120) || !isText(p.shows, 700)) { errs.push(`conformance.proofs: bad proof ${JSON.stringify(p && p.id)}`); continue; }
    proofIds.add(p.id);
  }
  const item = (x, at) => {
    if (!isScore(x.score) || !isCount(x.points) || !isCount(x.total) || !isCount(x.skipped) || x.points > x.total) errs.push(`${at}: bad score, points, total or skipped`);
    if (!DEPTHS.includes(x.depth)) errs.push(`${at}: bad depth ${JSON.stringify(x.depth)}`);
    if (!Array.isArray(x.proofs) || !x.proofs.every((id) => proofIds.has(id))) errs.push(`${at}: proofs must name proofs of the list`);
  };
  if (!Array.isArray(C.x11)) errs.push('conformance.x11 must be a list');
  else for (const x of C.x11) {
    const at = `conformance.x11 ${x && RE_X11.test(x.id || '') ? x.id : JSON.stringify(x && x.id)}`;
    if (!x || !RE_X11.test(x.id || '') || !isText(x.title, 200)) { errs.push(`${at}: bad id or title`); continue; }
    item(x, at);
  }
  if (!Array.isArray(C.globals)) errs.push('conformance.globals must be a list');
  else for (const g of C.globals) {
    const at = `conformance.globals ${g && RE_GLOBAL.test(g.global || '') ? g.global : JSON.stringify(g && g.global)}`;
    if (!g || !RE_GLOBAL.test(g.global || '') || !ids.has(g.row) || !(g.version === null || isVersion(g.version)) || typeof g.advertised !== 'boolean') { errs.push(`${at}: bad global, row, version or advertised`); continue; }
    item(g, at);
  }
  return proofIds;
}

// the site's copy (web/content/wayland/protocols.json), checked again by web/build.mjs before it renders anything
export function validateWeb(w) {
  const errs = [];
  if (!w || !w.compared || !Array.isArray(w.protocols) || !w.stats) return ['not a wayland table'];
  const c = w.compared;
  if (!RE_DATE.test(c.date || '') || c.source !== 'https://wayland.app/protocols/') errs.push('compared: bad date or source');
  for (const k of ['kwin', 'mutter']) if (!c[k] || !RE_CVER.test(String(c[k].version)) || !RE_DATE.test(c[k].dataDate || '')) errs.push(`compared.${k}: bad version or date`);
  for (const [k, v] of Object.entries(w.stats)) if (k !== 'gaps' && !(Number.isInteger(v) && v >= 0)) errs.push(`stats.${k} must be a count`);
  const ver = (v) => v === null || isVersion(v);
  const ids = new Set(w.protocols.map((p) => p && p.id).filter((id) => typeof id === 'string' && RE_ID.test(id)));
  const proofIds = validateConfWeb(w.conformance === undefined ? null : w.conformance, ids, errs);
  for (const p of w.protocols) {
    const at = `${typeof p.id === 'string' && RE_ID.test(p.id) ? p.id : JSON.stringify(p.id)}:`;
    if (typeof p.id !== 'string' || !RE_ID.test(p.id)) errs.push(`${at} bad id`);
    if (!CATEGORIES.includes(p.cat)) errs.push(`${at} bad category ${JSON.stringify(p.cat)}`);
    if (typeof p.url !== 'string' || !RE_URL.test(p.url)) errs.push(`${at} bad url`);
    if (!isText(p.name, 120) || !isText(p.summary, 300)) errs.push(`${at} bad name or summary`);
    if (!Array.isArray(p.globals) || !p.globals.every((g) => typeof g === 'string' && RE_GLOBAL.test(g))) errs.push(`${at} bad globals`);
    if (!ver(p.kwin) || !ver(p.mutter)) errs.push(`${at} bad KWin or Mutter version`);
    const L = p.lordos || {};
    if (!STATUSES.includes(L.status)) errs.push(`${at} bad status ${JSON.stringify(L.status)}`);
    if (!ver(L.version)) errs.push(`${at} bad LordOS version`);
    for (const k of ['since', 'bumped']) if (L[k] !== null && !RE_VER.test(L[k] || '')) errs.push(`${at} bad ${k}`);
    if (!isText(L.note) || !isText(L.checked, 200) || !RE_DATE.test(L.checkedDate || '')) errs.push(`${at} bad note, checked or checkedDate`);
    const F = p.conf === undefined ? null : p.conf;
    if (F !== null && (!F || typeof F !== 'object' || !isScore(F.score) || !isCount(F.points) || !isCount(F.total) || F.points > F.total || !isCount(F.skipped) || !DEPTHS.includes(F.depth)
      || !Array.isArray(F.globals) || !F.globals.every((g) => typeof g === 'string' && RE_GLOBAL.test(g)) || !Array.isArray(F.proofs) || !F.proofs.every((id) => proofIds.has(id)))) errs.push(`${at} bad conf`);
  }
  return errs;
}

// ---------- conformance (docs/wayland-conformance.json, written by tools/wl-conformance.mjs --record) ----------
export function confDepth(g) {
  if (g.complete) return 'complete';
  if (String(g.depth).startsWith('protocol-specific')) return 'partial';   /* "(test hooks)": not advertised to a normal client */
  if (g.depth === 'generic only') return 'general';
  return 'code';
}
export function x11Depth(i) {
  if (i.complete) return 'complete';
  const kinds = new Set((i.checks || []).map((c) => c.kind));
  return kinds.has('dynamic') ? 'partial' : kinds.has('unit') ? 'general' : 'code';
}
const round1 = (x) => Math.round(x * 10) / 10;
// the proofs: proofs.json's Wayland programs, then every x11-*.png (its item from the name)
export function confProofs(C) {
  const out = [];
  for (const r of (C.proofs && C.proofs.results) || []) if (r.result === 'pass' && r.png) out.push({ id: r.name, png: r.png, kind: 'wayland', app: r.app, version: r.version, shows: r.shows });
  const items = new Map(((C.xwayland && C.xwayland.items) || []).map((i) => [i.id, i]));
  for (const f of (C.proofFiles || []).filter((x) => x.startsWith('x11-'))) {
    const id = X11_PROOF_ITEM[f] || f.slice(4, -4);
    const it = items.get(id);
    out.push({ id: f.slice(0, -4), png: f, kind: 'x11', item: id, app: 'Xwayland', version: 'Xwayland ' + ((C.environment || {}).xwayland || ''), shows: it ? it.title : id });
  }
  return out;
}
// a proof proves a global when its name holds the global (wl_subcompositor-wp_viewporter, xdg_wm_base-foot)
const proofsOf = (proofs, global) => proofs.filter((p) => p.kind === 'wayland' && p.id.split('-').includes(global)).map((p) => p.id);
export function confRows(d, C) {
  const rowOf = new Map();
  for (const p of d.protocols) for (const g of Object.keys(p.lordos.globals || {})) if (!rowOf.has(g)) rowOf.set(g, p.id);
  const proofs = confProofs(C);
  return C.protocols.map((g) => ({ global: g.global, row: rowOf.get(g.global) || null, version: g.version ?? null, advertised: g.advertised !== false,
    score: round1(g.score), points: g.points, total: g.total, skipped: g.skipped, depth: confDepth(g), proofs: proofsOf(proofs, g.global) }))
    .sort((a, b) => a.global.localeCompare(b.global));
}
export function confX11(C) {
  const proofs = confProofs(C);
  return ((C.xwayland && C.xwayland.items) || []).map((i) => ({ id: i.id, title: i.title, score: round1(i.score), points: i.points, total: i.total,
    skipped: i.skipped, depth: x11Depth(i), proofs: proofs.filter((p) => p.item === i.id).map((p) => p.id) }));
}
export function confWeb(d, C) {
  if (!C) return null;
  const E = C.environment || {}, S = C.summary || {}, x11 = confX11(C);
  return {
    date: C.date, commit: String(C.commit).slice(0, 8), dirty: !!C.dirty, tool: C.tool, schema: C.schema,
    env: { waylandProtocols: E.wayland_protocols, libwayland: E.libwayland, xwayland: E.xwayland, mode: E.mode },
    summary: { protocols: S.protocols, complete: S.complete, mean: S.mean, x11Items: x11.length, x11Complete: x11.filter((x) => x.depth === 'complete').length, x11Mean: S.x11_mean },
    globals: confRows(d, C), x11,
    proofs: confProofs(C).map(({ id, png, kind, app, version, shows }) => ({ id, png, kind, app, version, shows })),
  };
}
// a row's conformance: its globals' together (points summed; the shallowest depth)
function rowConf(p, globals) {
  const gs = globals.filter((g) => g.row === p.id);
  if (!gs.length) return null;
  const points = gs.reduce((a, g) => a + g.points, 0), total = gs.reduce((a, g) => a + g.total, 0);
  return { score: total ? round1((100 * points) / total) : 0, points, total, skipped: gs.reduce((a, g) => a + g.skipped, 0),
    depth: DEPTHS[Math.max(...gs.map((g) => DEPTHS.indexOf(g.depth)))], globals: gs.map((g) => g.global), proofs: [...new Set(gs.flatMap((g) => g.proofs))] };
}

export function stats(d) {
  const P = d.protocols;
  const on = (p) => p.lordos.status === 'supported' || p.lordos.status === 'partial';
  const both = P.filter((p) => has(p.kwin) && has(p.mutter));
  const either = P.filter((p) => has(p.kwin) || has(p.mutter));
  return {
    total: P.length,
    lordos: P.filter(on).length,
    kwin: P.filter((p) => has(p.kwin)).length,
    mutter: P.filter((p) => has(p.mutter)).length,
    both: both.length, lordosOfBoth: both.filter(on).length,
    either: either.length, lordosOfEither: either.filter(on).length,
    onPurpose: P.filter((p) => p.lordos.status === 'on-purpose').length,
    missing: P.filter((p) => p.lordos.status === 'missing').length,
    // what both desktops offer and LordOS doesn't, nor leaves out on purpose
    gaps: both.filter((p) => p.lordos.status === 'missing').map((p) => p.id),
  };
}

// (b) the site's data: only what the page shows
export function webData(d, C = null) {
  const conformance = confWeb(d, C);
  return {
    compared: d.compared, stats: stats(d), conformance,
    protocols: d.protocols.map((p) => ({
      id: p.id, name: p.name, cat: category(p), deprecated: !!p.deprecated, summary: p.summary, url: p.url,
      globals: p.globals,
      kwin: ver(p, p.kwin), mutter: ver(p, p.mutter),
      lordos: { status: p.lordos.status, version: ver(p, p.lordos.globals), since: p.lordos.since || null,
        bumped: Object.values(p.lordos.bumped || {}).map((b) => b.in).sort().pop() || null, note: p.lordos.note || '', checked: p.lordos.checked, checkedDate: p.lordos.checkedDate },
      conf: conformance ? rowConf(p, conformance.globals) : null,
    })),
  };
}

const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
// (a) the Markdown section
export function markdown(d) {
  const c = d.compared, s = stats(d);
  const K = `KWin ${c.kwin.version}`, M = `Mutter ${c.mutter.version}`;
  const lordosCell = (p) => {
    const L = p.lordos, v = ver(p, L.globals);
    if (L.status === 'on-purpose') return 'no, on purpose';
    if (L.status === 'missing') return '—';
    const bump = Object.values(L.bumped || {})[0];
    return `${L.status === 'partial' ? 'partly, ' : ''}${v}${L.since ? ` (since ${L.since})` : ''}${bump ? ` (${bump.from} before ${bump.in})` : ''}`;
  };
  const rows = d.protocols.map((p) => `| [${cell(p.id)}](${p.url})${p.deprecated ? ' (deprecated)' : ''} | ${category(p)} | ${lordosCell(p)} | ${ver(p, p.kwin) ?? '—'} | ${ver(p, p.mutter) ?? '—'} | ${cell(p.lordos.note || '')} |`);
  return [
    BEGIN,
    '',
    `Compared on ${c.date}: LordOS's own globals (\`server/src/wl/*.c\`) against ${c.kwin.desktop}'s ${K} and ${c.mutter.desktop}'s ${M} as [wayland.app](${c.source}) lists them`,
    `(its data from ${c.kwin.dataDate} and ${c.mutter.dataDate}: the globals each advertised to an ordinary client, so protocols a compositor keeps for its own`,
    'trusted programs show as not offered). The number is the version of the protocol\'s first global; "—" is not advertised. Published as',
    '[lordos.org/wayland-protocols-table](https://lordos.org/wayland-protocols-table/). To change a row, edit `docs/wayland-protocols.json` and run',
    '`node tools/gen-wayland-table.mjs`; `server/tests/wayland_table_test.mjs` fails when the JSON and `server/src/wl` disagree.',
    '',
    `${s.total} protocols. LordOS offers ${s.lordos}; ${K} ${s.kwin}; ${M} ${s.mutter}. Of the ${s.both} that both KWin and Mutter offer, LordOS offers ${s.lordosOfBoth};`,
    `${s.onPurpose} are left out on purpose and ${s.missing} are not offered (yet).${s.gaps.length ? ` Offered by both and not by LordOS: ${s.gaps.map((g) => '`' + g + '`').join(', ')}.` : ''}`,
    '',
    `| Protocol | Category | LordOS | ${K} | ${M} | Note |`,
    '|---|---|---|---|---|---|',
    ...rows,
    '',
    END,
  ].join('\n');
}

const DEPTH_MD = { complete: 'complete', partial: 'partial', general: 'general', code: 'code only' };
const pct = (x) => `${x} %`;
// (a') the per-item conformance table, inside "## Conformance"
export function confMarkdown(d, C) {
  const W = confWeb(d, C);
  if (!W) return `${CBEGIN}\n\nNo run recorded (docs/wayland-conformance.json).\n\n${CEND}`;
  const S = W.summary, E = W.env;
  const pts = (x) => `${x.points}/${x.total}${x.skipped ? ` (${x.skipped} skipped)` : ''}`;
  const g = W.globals.map((x) => `| \`${x.global}\`${x.advertised ? '' : ' (not advertised to an ordinary client; run through the test hooks)'} | ${x.row ? `\`${x.row}\`` : '—'} | ${x.version ?? '—'} | ${pct(x.score)} | ${pts(x)} | ${DEPTH_MD[x.depth]} |`);
  const x = W.x11.map((i) => `| \`${i.id}\` | ${cell(i.title)} | ${pct(i.score)} | ${pts(i)} | ${DEPTH_MD[i.depth]} |`);
  return [
    CBEGIN,
    '',
    `Every item of the recorded run: ${W.date}, \`${W.tool}\` (report schema ${W.schema}) at commit \`${W.commit}\`${W.dirty ? ' with uncommitted changes' : ''};`,
    `wayland-protocols ${E.waylandProtocols}, libwayland ${E.libwayland}, Xwayland ${E.xwayland}; ${E.mode}. Published with the screenshots on`,
    '[lordos.org/wayland-protocols-table](https://lordos.org/wayland-protocols-table/#conformance). **Depth**: *complete* = protocol-specific',
    'tests of every request, event and error, all passed and nothing skipped (pointer, graphics tablet, VR headset and',
    'Xwayland\'s connection come from lord-server\'s `--test-hooks`, headless only); *partial* = protocol-specific tests, with',
    'a point skipped headless; *general* = the static code check and the generic bind at every version (X11: the static',
    'check and the unit tests), no flow of its own yet; *code only* = the static code check alone (X11: nothing to run headless).',
    '',
    `**Wayland: ${S.protocols} globals, mean ${pct(S.mean)}, ${S.complete} complete.**`,
    '',
    '| Global | Protocol (table row) | Version | Score | Points | Depth |',
    '|---|---|---|---|---|---|',
    ...g,
    '',
    `**X11 / Xwayland: ${S.x11Items} items, mean ${pct(S.x11Mean)}, ${S.x11Complete} complete.**`,
    '',
    '| Item | What | Score | Points | Depth |',
    '|---|---|---|---|---|',
    ...x,
    '',
    CEND,
  ].join('\n');
}
// the conformance block sits right before "**Proof with real programs**" in "## Conformance" (first run), then stays put
export function withConfSection(md, section) {
  const a = md.indexOf(CBEGIN), b = md.indexOf(CEND);
  if (a >= 0 && b > a) return md.slice(0, a) + section + md.slice(b + CEND.length);
  const at = md.indexOf('\n**Proof with real programs**');
  return at >= 0 ? md.slice(0, at + 1) + section + '\n\n' + md.slice(at + 1) : md + '\n' + section + '\n';
}

export function withSection(md, section) {
  const a = md.indexOf(BEGIN), b = md.indexOf(END);
  if (a >= 0 && b > a) return md.slice(0, a) + section + md.slice(b + END.length);
  // first run: a section of its own before "## Pending"
  const at = md.indexOf('\n## Pending');
  const block = `\n## Protocol table (generated)\n\n${section}\n`;
  return at >= 0 ? md.slice(0, at) + block + md.slice(at) : md + block;
}

function main() {
  const check = process.argv.includes('--check');
  const d = load();
  const errs = validate(d);
  if (errs.length) { console.error('docs/wayland-protocols.json:\n  ' + errs.join('\n  ')); process.exit(1); }
  const C = loadConf();
  const md = fs.readFileSync(DOC, 'utf8');
  const wantMd = withConfSection(withSection(md, markdown(d)), confMarkdown(d, C));
  const web = webData(d, C);
  const werrs = validateWeb(web);
  if (werrs.length) { console.error('the site\'s copy would be refused:\n  ' + werrs.join('\n  ')); process.exit(1); }
  const wantWeb = JSON.stringify(web, null, 1) + '\n';
  const haveWeb = fs.existsSync(WEB) ? fs.readFileSync(WEB, 'utf8') : '';
  if (check) {
    const stale = [md !== wantMd && 'docs/WAYLAND.md', haveWeb !== wantWeb && path.relative(REPO, WEB)].filter(Boolean);
    if (stale.length) { console.error(`stale: ${stale.join(', ')}; run node tools/gen-wayland-table.mjs`); process.exit(1); }
    console.log('wayland table: up to date');
    return;
  }
  if (md !== wantMd) fs.writeFileSync(DOC, wantMd);
  fs.mkdirSync(path.dirname(WEB), { recursive: true });
  if (haveWeb !== wantWeb) fs.writeFileSync(WEB, wantWeb);
  const s = stats(d);
  console.log(`wayland table: ${s.total} protocols; LordOS ${s.lordos}, KWin ${s.kwin}, Mutter ${s.mutter}; LordOS ${s.lordosOfBoth} of the ${s.both} both offer; ${s.onPurpose} on purpose, ${s.missing} missing`);
  if (web.conformance) { const S = web.conformance.summary; console.log(`conformance (${web.conformance.date}): ${S.protocols} globals, mean ${S.mean} %, ${S.complete} complete; X11 ${S.x11Items} items, mean ${S.x11Mean} %; ${web.conformance.proofs.length} screenshots`); }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
